-- Shop metadata follows the existing service-role-only write pattern.
create table if not exists public.merch_items (
    id bigint generated by default as identity primary key,
    description text not null check (char_length(description) between 1 and 10000),
    image_url text not null,
    image_key text not null,
    created_at timestamptz not null default now(),
    deleted_at timestamptz
);

alter table public.merch_items enable row level security;
revoke all on public.merch_items from anon, authenticated;
grant all on public.merch_items to service_role;
grant usage, select on sequence public.merch_items_id_seq to service_role;
